"""FGAC compiler: turns the policy export tables into generated secured views.

Steps (run as the compiler service principal, which owns the catalog and the views):
  entitlements  governance.assoc_scope: each associate's scope nodes from assoc_dim (market:, region:, department:,
                reports_to: for every manager above them).
                governance.user_entitlement: one row per user. For every (classification, category) pair the user may
                see, the union of the scopes of the personas that grant it, so a grant never reaches beyond the
                scope of the persona that gives it. Only changed users are merged; every change is kept in
                governance.user_entitlement_history.
  views         one secured view per classified base table, hr_secure.<table>_vw. Each sensitive column becomes
                CASE WHEN <this user may see this pair on this row> THEN value END. A view is recreated only when the
                column classification or the base table's columns change, or when its stored definition was edited.
                Persona, scope and assignment changes never touch a view: they change the entitlement rows only.
  audit         the audit views in the audit schema, over the Databricks system tables (Unity Catalog audit log, query
                history) and the governance history: who read which secured view, every statement on the catalog,
                direct reads of the restricted tables, every governance change (privileges, owners, objects) and who
                made it, every entitlement change. Read by the admin and the configured auditors only.
  guard         revokes every privilege on the restricted schemas (hr_base, policy, governance), every catalog
                privilege other than USE CATALOG, and anything on the audit schema but the auditors' read, except for
                the owner and the admin.
Run: python3 -I compiler/fgac_compiler.py [entitlements|views|audit|guard|all]   (locally: --as compiler)
"""
import argparse
import hashlib
import json
import os
import sys
import time
import uuid

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(globals().get("__file__") or sys.argv[0])), ".."))
import config  # noqa: E402
import dbsql  # noqa: E402

C, X, G = config.CATALOG, f"{config.CATALOG}.{config.EXPORTS}", f"{config.CATALOG}.{config.GOV}"
BASE, SECURE, AUDIT = config.BASE, config.SECURE, config.AUDIT
SOURCES = config.EXPORT_TABLES
VIEW_COMMENT = "Generated by the FGAC compiler from the column classifications. Do not edit: it is recreated."
OWNER_TERM = "Associate ID"  # the business term of the column that says whose record a row is
# "Payroll & Tax" -> payroll_and_tax
NORM = "regexp_replace(lower(replace({0}, '&', 'and')), '[^a-z0-9]+', '_')"
SCOPE_NODE = {"Market": "market", "Region": "region", "Department": "department", "Reporting": "reports_to"}
w = None


def q(sql):
    return dbsql.run(w, sql, quiet=True)[1]


def source_versions():
    return {t: int(q(f"DESCRIBE HISTORY {X}.{t} LIMIT 1")[0][0]) for t in SOURCES}


def log(step, t0, detail, versions):
    vs = ", ".join(f"'{k}', {v}" for k, v in versions.items())
    q(f"""INSERT INTO {G}.compile_log VALUES ('{uuid.uuid4()}', '{step}', current_timestamp(), {time.time() - t0:.1f},
          session_user(), '{sql_text(detail)}', CAST(map({vs}) AS MAP<STRING, BIGINT>))""")


def lit(s):
    """A name inside a '...' literal."""
    return s.replace("'", "''")


def sql_text(s):
    """Free text (server messages, object names) made safe inside a '...' literal and for config.render: no quote or
    backslash can end the literal, and no {{NAME}} is left for render to fill."""
    return s.replace("\\", "/").replace("'", "").replace("{{", "{ {").replace("}}", "} }")


def ensure_tables():
    q(f"""CREATE TABLE IF NOT EXISTS {G}.user_entitlement (user_principal STRING, own_win BIGINT, sees_rows BOOLEAN,
  personas ARRAY<STRING>, grants MAP<STRING, STRUCT<all_rows: BOOLEAN, nodes: ARRAY<STRING>, own: BOOLEAN>>,
  ent_hash STRING, compiled_at TIMESTAMP)
CLUSTER BY (user_principal)
COMMENT 'One row per user, compiled from the policy exports. Read only by the secured views.'""")
    # every query reads one row of it (the person asking): clustering on user_principal lets the read skip the rest
    q(f"""CREATE TABLE IF NOT EXISTS {G}.user_entitlement_history (user_principal STRING, own_win BIGINT, sees_rows BOOLEAN,
  personas ARRAY<STRING>, grants MAP<STRING, STRUCT<all_rows: BOOLEAN, nodes: ARRAY<STRING>, own: BOOLEAN>>,
  ent_hash STRING, change_type STRING, valid_from TIMESTAMP, valid_to TIMESTAMP)
COMMENT 'Every version of every user entitlement (who could see what, when)'""")
    q(f"""CREATE TABLE IF NOT EXISTS {G}.compile_log (run_id STRING, step STRING, run_at TIMESTAMP, duration_s DOUBLE,
  run_by STRING, detail STRING, source_versions MAP<STRING, BIGINT>)
COMMENT 'One row per compiler step run, with the export table versions it read'""")
    q(f"""CREATE TABLE IF NOT EXISTS {G}.generated_views (view_name STRING, base_table STRING, desired_sha STRING,
  stored_sha STRING, generated_at TIMESTAMP)
COMMENT 'Each secured view as the compiler generated it: sha2 of the generated SQL and of the definition as stored'""")
    q(f"""CREATE TABLE IF NOT EXISTS {G}.audit_views (view_name STRING, desired_sha STRING, stored_sha STRING,
  generated_at TIMESTAMP)
COMMENT 'Each audit view as the compiler generated it: sha2 of the generated SQL and of the definition as stored'""")


# ---------------------------------------------------------------------------------------------------- entitlements
SCOPE_FORMAT = "1"  # bump when the scope node format changes: the scope tables are then rebuilt


def scope_source_tag():
    """What the scope tables are built from: assoc_dim's table ID (a dropped and re-created table is a new table) and its
    last version that changed data (maintenance such as OPTIMIZE does not count), plus the node format."""
    cols, rows = dbsql.run(w, f"DESCRIBE DETAIL {X}.assoc_dim", quiet=True)
    table_id = rows[0][cols.index("id")]
    cols, rows = dbsql.run(w, f"DESCRIBE HISTORY {X}.assoc_dim LIMIT 100", quiet=True)
    v, op = cols.index("version"), cols.index("operation")
    data = [int(r[v]) for r in rows if r[op] not in config.MAINTENANCE_OPS]
    return f"{SCOPE_FORMAT}:{table_id}:{max(data) if data else int(rows[0][v])}"


def built_from(table):
    """The scope_source_tag a scope table was built from (its table property), or None."""
    if not q(f"SHOW TABLES IN {G} LIKE '{table}'"):
        return None
    cols, rows = dbsql.run(w, f"DESCRIBE DETAIL {G}.{table}", quiet=True)
    props = rows[0][cols.index("properties")] if rows else None
    props = json.loads(props) if isinstance(props, str) else (props or {})
    return props.get("fgac.built_from")


def compile_entitlements():
    t0, versions = time.time(), source_versions()
    ensure_tables()
    tag = scope_source_tag()
    if built_from("assoc_scope") != tag:  # rebuilt only when assoc_dim's data changed
        q(f"""CREATE OR REPLACE TABLE {G}.assoc_scope
COMMENT 'Each associate''s scope nodes, from assoc_dim (resolved hierarchies). Read only by the secured views.'
TBLPROPERTIES ('fgac.built_from' = '{tag}') AS
SELECT win, array_sort(array_distinct(flatten(collect_list(array_compact(concat(
         array(concat('market:', market), concat('region:', region), concat('department:', department)),
         transform(coalesce(reporting_chain, array()), m -> concat('reports_to:', CAST(m AS STRING))))))))) AS nodes
FROM {X}.assoc_dim GROUP BY win""")  # one row per associate: several assoc_dim rows must never duplicate view rows
    if config.SCOPE_CHECK == "join":  # the same nodes, one row per (associate, node), for the join form of the views
        if built_from("assoc_scope_node") != tag:  # only when assoc_dim changed
            q(f"""CREATE OR REPLACE TABLE {G}.assoc_scope_node CLUSTER BY (node)
COMMENT 'assoc_scope, one row per (associate, scope node). Read only by the secured views (scope_check: join).'
TBLPROPERTIES ('fgac.built_from' = '{tag}') AS
SELECT win, node FROM {G}.assoc_scope LATERAL VIEW explode(nodes) n AS node""")
            q(f"OPTIMIZE {G}.assoc_scope_node")
    else:  # array form: no node table, so a stale one can never be read (join-form views fail closed until rebuilt)
        q(f"DROP TABLE IF EXISTS {G}.assoc_scope_node")
    unclassified = (f"UNION SELECT DISTINCT persona_id, 'unclassified' FROM {X}.persona_column_policy "
                    f"WHERE {NORM.format('classification')} = 'highly_sensitive' AND data_security_category IS NOT NULL") \
        if config.UNCLASSIFIED_RULE == "highly_sensitive" else ""
    run = uuid.uuid4().hex[:12]  # staging tables per run: two runs (the jobs, a hand run) never share them
    SE, SC = f"{G}._stage_entitlement_{run}", f"{G}._stage_changed_{run}"
    node = "CASE p.scope_type " + " ".join(f"WHEN '{k}' THEN concat('{v}:', r.scope_value)" for k, v in SCOPE_NODE.items()) + " END"
    q(f"""CREATE OR REPLACE TABLE {SE} AS
WITH persona AS (  -- a persona listed with two scope types is ambiguous: it grants nothing until the export is fixed
  SELECT persona_id, min(scope_type) AS scope_type FROM {X}.persona
  WHERE persona_id IS NOT NULL GROUP BY persona_id HAVING count(DISTINCT scope_type) = 1),
roles AS (  -- a row without a login can't be anyone's
  SELECT lower(r.user_principal) AS user_principal, r.win, r.persona_id, p.scope_type, {node} AS node
  FROM {X}.assoc_roles_dim r JOIN persona p USING (persona_id) WHERE r.user_principal IS NOT NULL),
pairs AS (  -- the (classification, category) pairs each persona grants
  SELECT DISTINCT persona_id, concat({NORM.format('classification')}, '__', {NORM.format('data_security_category')}) AS k
  FROM {X}.persona_column_policy
  WHERE classification IS NOT NULL AND data_security_category IS NOT NULL  -- a partial pair grants nothing
  {unclassified}),
persona_scope AS (  -- the scope of each persona a user holds; an unknown scope type gives no scope (fails closed)
  SELECT user_principal, persona_id, bool_or(scope_type = 'Enterprise') AS all_rows, bool_or(scope_type = 'Self') AS own,
         array_compact(collect_set(node)) AS nodes
  FROM roles GROUP BY user_principal, persona_id),
pair_scope AS (  -- union, per pair, of the scopes of the personas that grant that pair
  SELECT s.user_principal, p.k, bool_or(s.all_rows) AS all_rows, bool_or(s.own) AS own,
         array_sort(array_distinct(flatten(collect_list(s.nodes)))) AS nodes
  FROM persona_scope s JOIN pairs p USING (persona_id) GROUP BY s.user_principal, p.k),
users AS (
  -- a login listed with two different wins has no own record (no Self) until the export is fixed
  SELECT user_principal, CASE WHEN count(DISTINCT win) = 1 THEN max(win) END AS own_win, bool_or(scope_type <> 'Self') AS sees_rows,
         array_sort(collect_set(persona_id)) AS personas
  FROM roles GROUP BY user_principal),
leavers AS (  -- a login any of whose wins has left
  SELECT DISTINCT r.user_principal FROM roles r JOIN {X}.assoc_dim d ON d.win = r.win WHERE d.status IN ({config.TERMINATED_SQL})),
grants AS (
  SELECT user_principal, map_from_entries(array_sort(collect_list(struct(k,
           named_struct('all_rows', all_rows, 'nodes', nodes, 'own', own))))) AS grants
  FROM pair_scope GROUP BY user_principal)
SELECT u.user_principal, u.own_win, u.sees_rows, u.personas,
       coalesce(g.grants, CAST(map() AS MAP<STRING, STRUCT<all_rows: BOOLEAN, nodes: ARRAY<STRING>, own: BOOLEAN>>)) AS grants,
       sha2(to_json(struct(u.own_win, u.sees_rows, u.personas, g.grants)), 256) AS ent_hash, current_timestamp() AS compiled_at
FROM users u LEFT JOIN grants g USING (user_principal)
LEFT ANTI JOIN leavers l USING (user_principal)  -- a person who has left loses everything, even if assoc_roles_dim lists personas""")
    try:
        _merge(SE, SC, versions, t0)
    finally:  # never leave staging copies of the entitlements behind
        for t in (SE, SC):
            q(f"DROP TABLE IF EXISTS {t}")


def _merge(SE, SC, versions, t0):
    # also against the open history version: if a run stopped after the MERGE but before the history writes, the user
    # comes back here and the lost history version is written
    q(f"""CREATE OR REPLACE TABLE {SC} AS
WITH h AS (  -- the open version; if a hand run overlapped the job and left two, the newest (the UPDATE closes both)
  SELECT user_principal, max_by(ent_hash, valid_from) AS ent_hash FROM {G}.user_entitlement_history
  WHERE valid_to IS NULL GROUP BY user_principal)
SELECT coalesce(s.user_principal, t.user_principal, h.user_principal) AS user_principal,
       CASE WHEN s.user_principal IS NULL THEN 'REVOKED'
            WHEN t.user_principal IS NULL AND h.user_principal IS NULL THEN 'GRANTED' ELSE 'CHANGED' END AS change_type
FROM {SE} s FULL OUTER JOIN {G}.user_entitlement t USING (user_principal)
FULL OUTER JOIN h ON h.user_principal = coalesce(s.user_principal, t.user_principal)
WHERE s.ent_hash IS DISTINCT FROM t.ent_hash OR s.ent_hash IS DISTINCT FROM h.ent_hash""")
    changes = dict((k, int(v)) for k, v in q(f"SELECT change_type, count(*) FROM {SC} GROUP BY 1"))
    if changes:
        q(f"""MERGE INTO {G}.user_entitlement t
USING (SELECT c.user_principal, c.change_type, s.* EXCEPT (user_principal)
       FROM {SC} c LEFT JOIN {SE} s USING (user_principal)) s
ON t.user_principal = s.user_principal
WHEN MATCHED AND s.change_type = 'REVOKED' THEN DELETE
WHEN MATCHED THEN UPDATE SET own_win = s.own_win, sees_rows = s.sees_rows, personas = s.personas, grants = s.grants,
  ent_hash = s.ent_hash, compiled_at = s.compiled_at
WHEN NOT MATCHED AND s.change_type <> 'REVOKED' THEN INSERT (user_principal, own_win, sees_rows, personas, grants, ent_hash, compiled_at)
  VALUES (s.user_principal, s.own_win, s.sees_rows, s.personas, s.grants, s.ent_hash, s.compiled_at)""")
        q(f"""UPDATE {G}.user_entitlement_history SET valid_to = current_timestamp()
WHERE valid_to IS NULL AND user_principal IN (SELECT user_principal FROM {SC})""")
        q(f"""INSERT INTO {G}.user_entitlement_history
SELECT c.user_principal, s.own_win, coalesce(s.sees_rows, false), coalesce(s.personas, array()), s.grants, s.ent_hash,
       c.change_type, current_timestamp(), CASE WHEN c.change_type = 'REVOKED' THEN current_timestamp() END
FROM {SC} c LEFT JOIN {SE} s USING (user_principal)""")
    n = q(f"SELECT count(*) FROM {G}.user_entitlement")[0][0]
    log("entitlements", t0, str(changes or "no changes"), versions)
    print(f"entitlements: {n} users; changes {changes or 'none'} ({time.time() - t0:.0f}s)")


# ---------------------------------------------------------------------------------------------------- views
def view_name(table):
    return f"{table}{config.VIEW_SUFFIX}"


def visible(key, owner):
    """SQL: may the querying user (e) see a value of grant key `key` on this row (b, its associate's scope s)?
    e holds the user's grants already flattened to one column per key (see user_grants), so nothing is looked up per row."""
    if owner is None:  # no associate key: only an enterprise-wide grant reaches the row
        return f"e.`a__{key}`"
    covered = (f"coalesce(vis.`v__{key}`, false)" if config.SCOPE_CHECK == "join"
               else f"coalesce(arrays_overlap(e.`n__{key}`, s.nodes), false)")
    return f"(e.`a__{key}` OR (e.`o__{key}` AND b.`{owner}` = e.own_win) OR {covered})"


def visible_set(keys, owner):
    """SQL (scope_check: join): the associates the querying user's scoped personas reach, one row per associate with a
    v__ flag per key, built once per query by joining the user's (key, node) list to assoc_scope_node. Keys an
    enterprise-wide persona grants are left out: they need no node."""
    flags = ", ".join(f"bool_or(g.k = '{k}') AS `v__{k}`" for k in sorted(keys))
    in_keys = ", ".join(f"'{k}'" for k in sorted(keys))
    return (f"LEFT JOIN (SELECT sn.win, {flags}\n"
            f"   FROM (SELECT t.k, n.node FROM {G}.user_entitlement u\n"
            f"         LATERAL VIEW explode(u.grants) t AS k, v LATERAL VIEW explode(v.nodes) n AS node\n"
            f"         WHERE u.user_principal = lower(session_user()) AND NOT coalesce(v.all_rows, false) AND t.k IN ({in_keys})) g\n"
            f"   JOIN {G}.assoc_scope_node sn ON sn.node = g.node GROUP BY sn.win) vis ON vis.win = b.`{owner}`\n")


def user_grants(keys, owner):
    """SQL: the querying user's entitlement row, its grants flattened once per query: for each key the table uses,
    a__ (an enterprise-wide grant), o__ (Self) and n__ (the scope nodes). So the map is never looked up per row or
    per cell, however many personas the user holds."""
    cols = []
    for k in sorted(keys):
        g = f"try_element_at(e.grants, '{k}')"
        cols.append(f"coalesce({g}.all_rows, false) AS `a__{k}`")
        if owner:
            cols.append(f"coalesce({g}.own, false) AS `o__{k}`")
            if config.SCOPE_CHECK == "array":
                cols.append(f"{g}.nodes AS `n__{k}`")
    return (f"(SELECT {', '.join(['e.own_win', 'e.sees_rows'] + cols)}\n"
            f"   FROM {G}.user_entitlement e WHERE e.user_principal = lower(session_user())) e")


def desired_views():
    """{view: (base table, SQL)} for every base table with at least one classified column."""
    cls = q(f"""SELECT lower(qualified_column_name), business_term,
                 CASE WHEN classification IS NULL AND data_security_category IS NULL THEN NULL
                      WHEN classification IS NULL OR data_security_category IS NULL THEN 'denied_incomplete'
                      ELSE concat({NORM.format('classification')}, '__', {NORM.format('data_security_category')}) END
               FROM {X}.column_classification
               ORDER BY 1, 3, 2""")  # deterministic: the same rows always give the same owner column and view
    by_table, skipped = {}, []
    for qcn, term, key in cls:
        parts = qcn.split(".")
        if len(parts) != 4 or parts[0] != C or parts[1] != BASE:  # the classification covers more than these tables
            skipped.append(qcn)
            continue
        col = by_table.setdefault(parts[2], {})
        if parts[3] in col and col[parts[3]][1] != key:  # the classification disagrees with itself: never pick one, deny the column
            print(f"views: WARNING the classification has conflicting rows for {qcn}: denied to everyone until it is fixed")
            col[parts[3]] = (term, "denied_conflict")
        elif parts[3] not in col:
            col[parts[3]] = (term, key)
    if skipped:
        print(f"views: {len(skipped)} classification row(s) are not columns of {C}.{BASE}: skipped (for example {', '.join(skipped[:3])})")
    cols = {}
    for t, c, dtype in q(f"""SELECT table_name, column_name, full_data_type FROM {C}.information_schema.columns
                             WHERE table_schema = '{BASE}' ORDER BY table_name, ordinal_position"""):
        cols.setdefault(t, []).append((c, dtype))
    out = {}
    for t, mapped in sorted(by_table.items()):
        phys = cols.get(t)
        if not phys:
            print(f"views: WARNING the classification maps {BASE}.{t}, which doesn't exist: no view")
            continue
        names = {p.lower() for p, _ in phys}
        for c in mapped:
            if c not in names:
                print(f"views: WARNING the classification maps {BASE}.{t}.{c}, which doesn't exist: ignored")
        owner = next((p for p, _ in phys if mapped.get(p.lower(), (None,))[0] == OWNER_TERM), None)
        select, keys = [], set()
        for c, dtype in phys:
            term, key = mapped.get(c.lower(), (None, None))
            if key and key.startswith("non_sensitive__"):  # visible to everyone who can see the row
                select.append(f"b.`{c}`")
            elif key is None and config.UNCLASSIFIED_RULE != "highly_sensitive":
                select.append(f"CAST(NULL AS {dtype}) AS `{c}`")
            else:  # classified, or unclassified under the Highly Sensitive rule
                keys.add(key or "unclassified")
                select.append(f"CASE WHEN {visible(key or 'unclassified', owner)} THEN b.`{c}` END AS `{c}`")
        scope = ""
        if owner and keys:
            scope = (visible_set(keys, owner) if config.SCOPE_CHECK == "join"
                     else f"LEFT JOIN {G}.assoc_scope s ON s.win = b.`{owner}`\n")
        sql = (f"SELECT {', '.join(select)}\nFROM {C}.{BASE}.`{t}` b\n"
               f"CROSS JOIN {user_grants(keys, owner)}\n" + scope
               + (f"WHERE e.sees_rows OR b.`{owner}` = e.own_win" if owner else "WHERE e.sees_rows"))
        out[view_name(t)] = (t, sql)
    return out


def drop(sql, v, failed, schema=SECURE, record="generated_views"):
    """Fail closed: drop an object from the views (or audit) schema and forget it. A drop that fails is reported (the
    job then fails) and the run goes on with the other views."""
    try:
        q(sql)
        q(f"DELETE FROM {G}.{record} WHERE view_name = '{lit(v)}'")
        return True
    except RuntimeError as err:
        failed.append(f"NOT DROPPED {v}")
        print(f"{'views' if schema == SECURE else 'audit'}: ERROR could not drop {schema}.{v}: {' '.join(str(err).split())[:160]}")
        return False


def generate_views():
    t0, versions = time.time(), source_versions()
    ensure_tables()
    want = desired_views()
    have = {v: (d, s) for v, _, d, s, _ in q(f"SELECT * FROM {G}.generated_views")}
    live = {v: d for v, d in q(f"""SELECT table_name, sha2(view_definition, 256) FROM {C}.information_schema.views
                                     WHERE table_schema = '{SECURE}'""")}
    made, failed = 0, []
    for v, (t, sql) in want.items():
        desired_sha = hashlib.sha256(sql.encode()).hexdigest()  # = SQL sha2(sql, 256)
        rec = have.get(v)
        if rec and rec[0] == desired_sha and live.get(v) == rec[1]:
            continue  # unchanged and not edited
        why = "new" if not rec else ("edited by hand" if rec[0] == desired_sha else "classification or columns changed")
        try:  # one table that can't be compiled (for example unreadable) must not hold back the other views
            q(f"CREATE OR REPLACE VIEW {C}.{SECURE}.`{v}` COMMENT '{VIEW_COMMENT}' AS {sql}")
        except RuntimeError as err:  # fail closed: an out-of-date view could show what the classification no longer allows
            failed.append(v)
            print(f"views: ERROR {SECURE}.{v} could not be (re)created: {' '.join(str(err).split())[:160]}")
            drop(f"DROP VIEW IF EXISTS {C}.{SECURE}.`{v}`", v, failed)
            continue
        stored = q(f"""SELECT sha2(view_definition, 256) FROM {C}.information_schema.views
                       WHERE table_schema = '{SECURE}' AND table_name = '{lit(v)}'""")[0][0]
        q(f"DELETE FROM {G}.generated_views WHERE view_name = '{lit(v)}'")
        q(f"INSERT INTO {G}.generated_views VALUES ('{lit(v)}', '{lit(t)}', '{desired_sha}', '{stored}', current_timestamp())")
        print(f"views: {SECURE}.{v} ({why})")
        made += 1
    # fail closed: a view whose table is no longer classified, or no longer exists, is dropped
    for v, kind in q(f"""SELECT table_name, table_type FROM {C}.information_schema.tables WHERE table_schema = '{SECURE}'"""):
        if kind == "VIEW" and v not in want:
            if drop(f"DROP VIEW {C}.{SECURE}.`{v}`", v, failed):
                print(f"views: dropped {SECURE}.{v} (its table has no classification or no longer exists)")
        elif kind != "VIEW":  # every user can read this schema: anything but a generated view could expose raw data
            what = {"MATERIALIZED_VIEW": "MATERIALIZED VIEW", "STREAMING_TABLE": "TABLE", "METRIC_VIEW": "VIEW"}.get(kind, "TABLE")
            if drop(f"DROP {what} {C}.{SECURE}.`{v}`", v, failed):
                print(f"views: WARNING dropped {SECURE}.{v} ({kind}): only generated views may be in {SECURE}")
    # every user can open this schema: a function (definer's rights) or a volume there could expose raw data too
    for f, in q(f"SELECT specific_name FROM {C}.information_schema.routines WHERE specific_schema = '{SECURE}'"):
        if drop(f"DROP FUNCTION {C}.{SECURE}.`{f}`", f, failed):
            print(f"views: WARNING dropped function {SECURE}.{f}: only generated views may be in {SECURE}")
    for vol, in q(f"SELECT volume_name FROM {C}.information_schema.volumes WHERE volume_schema = '{SECURE}'"):
        if drop(f"DROP VOLUME {C}.{SECURE}.`{vol}`", vol, failed):
            print(f"views: WARNING dropped volume {SECURE}.{vol}: only generated views may be in {SECURE}")
    # a view neither wanted nor present (dropped by hand with its table) leaves no record behind
    if want:
        q(f"DELETE FROM {G}.generated_views WHERE view_name NOT IN ({', '.join(chr(39) + lit(v) + chr(39) for v in want)})")
    else:
        q(f"DELETE FROM {G}.generated_views")
    # a failed run records no export versions: the freshness invariant keeps counting the classification change as not compiled
    log("views", t0, f"{len(want)} views, {made} (re)created" + (f", FAILED {failed}" if failed else ""), {} if failed else versions)
    if any(f.startswith("NOT DROPPED") for f in failed):
        print("views: ERROR an object in the views schema could not be dropped: fix it by hand (it may still be readable)")
    print(f"views: {len(want)} secured views, {made} (re)created ({time.time() - t0:.0f}s)")
    if failed:  # fail the job so it alerts; the views that could be built are in place
        raise RuntimeError(f"views not (re)created: {failed}")


# ---------------------------------------------------------------------------------------------------- audit
AUDIT_COMMENT = ("Generated by the FGAC compiler: an audit view over the Databricks system tables and the "
                 "governance history. Do not edit: it is recreated.")
# Unity Catalog audit actions that change governance: privileges, owners, and the objects themselves
CHANGE_ACTIONS = ("updatePermissions", "createCatalog", "updateCatalog", "deleteCatalog", "createSchema", "updateSchema",
                  "deleteSchema", "createTable", "updateTables", "deleteTable", "createFunction", "updateFunction",
                  "deleteFunction", "createVolume", "updateVolume", "deleteVolume", "createStagingTable")


def audit_views(me):
    """{view: SQL} for the audit schema. `me` is the compiler's identity (its own changes are flagged by_compiler).
    Every view keeps the system table's date (event_date) or time column: filter on it, the audit log is large."""
    c, m = lit(C), lit(me)
    secure, restricted = f"{c}.{SECURE}.", [f"{c}.{s}." for s in (BASE, config.EXPORTS, config.GOV)]
    # a read: Unity Catalog logs a READ snapshot when the warehouse fetches a table's credentials, with the securable the
    # query named (the secured view, or the table itself when someone reads it directly), however the query spelled
    # it. A result-cache answer reads no table, and a repeated read can reuse the credentials fetched shortly before:
    # the query history (statements) has every statement that names the catalog
    read = f"""FROM system.access.audit a
LATERAL VIEW explode(from_json(a.request_params.securables, 'ARRAY<STRUCT<type: STRING, full_name: STRING>>')) s AS o
WHERE a.service_name = 'unityCatalog' AND a.action_name = 'metadataAndPermissionsSnapshot'
  AND a.request_params.operation = 'READ' AND contains(a.request_params.securables, '{c}.')"""
    # the query history only has the text: a statement names the catalog as catalog.schema (backticks removed). One
    # that relies on USE CATALOG or the editor's catalog picker is not matched (its reads are in the audit log anyway)
    norm = "replace(lower(h.statement_text), '`', '')"
    names_catalog = f"contains({norm}, '{c.lower()}.')"

    def text(col):
        """SQL text and error messages can hold values someone typed (an INSERT's literals, a WHERE ssn = '...'
        probe): unless audit_statement_text is "full", string and number literals are replaced by ?"""
        if config.AUDIT_STATEMENT_TEXT == "full":
            return col
        return f"""regexp_replace(regexp_replace({col}, r"'([^']|'')*'", "'?'"), r"\\b[0-9]+([.][0-9]+)?\\b", "?")"""
    actions = ", ".join(f"'{x}'" for x in CHANGE_ACTIONS)
    views = {
        # with the personas the reader held then: the last entitlement version compiled before the read
        "view_reads": f"""SELECT r.read_at, r.event_date, r.reader, r.view_name, r.base_table, h.personas AS personas_then,
       r.status_code, r.workspace_id, r.source_ip_address, r.user_agent, r.request_id
FROM (SELECT a.event_time AS read_at, a.event_date, a.user_identity.email AS reader, o.full_name AS view_name,
             a.request_params.table_full_name AS base_table, a.response.status_code AS status_code,
             a.workspace_id, a.source_ip_address, a.user_agent, a.request_id
      {read}
        AND startswith(o.full_name, '{secure}')) r
LEFT JOIN {G}.user_entitlement_history h ON h.user_principal = lower(r.reader) AND h.valid_from <= r.read_at
QUALIFY row_number() OVER (PARTITION BY r.request_id, r.view_name ORDER BY h.valid_from DESC NULLS LAST) = 1""",
        # anyone but the compiler, from both records: the audit log's reads, and every statement (refused ones too)
        # that names a restricted schema; the auditors' own queries of the audit views are left out
        "restricted_reads": f"""SELECT a.event_time AS read_at, a.event_date, a.user_identity.email AS reader, 'audit log' AS source,
       o.full_name AS object_name, CAST(NULL AS STRING) AS statement_text, CAST(NULL AS STRING) AS execution_status,
       a.workspace_id, a.request_id AS id
{read}
  AND ({' OR '.join(f"startswith(o.full_name, '{r}')" for r in restricted)})
  AND a.user_identity.email IS DISTINCT FROM '{m}'
UNION ALL
SELECT h.start_time, CAST(h.start_time AS DATE), h.executed_by, 'query history', CAST(NULL AS STRING),
       {text('h.statement_text')}, h.execution_status, h.workspace_id, h.statement_id
FROM system.query.history h
WHERE h.executed_by IS DISTINCT FROM '{m}'
  AND ({' OR '.join(f"contains({norm}, '{r.lower()}')" for r in restricted)})
  AND NOT contains({norm}, '{c.lower()}.{AUDIT}.')""",
        "statements": f"""SELECT h.start_time, h.end_time, h.executed_by, h.executed_as, coalesce(h.executed_by = '{m}', false) AS by_compiler,
       h.statement_type, h.execution_status, {text('h.error_message')} AS error_message, h.from_result_cache,
       h.cache_origin_statement_id, h.produced_rows, h.total_duration_ms, h.compute.warehouse_id AS warehouse_id,
       h.workspace_id, h.client_application, h.statement_id, {text('h.statement_text')} AS statement_text
FROM system.query.history h
WHERE {names_catalog}""",
        "governance_changes": f"""SELECT changed_at, event_date, changed_by, coalesce(changed_by = '{m}', false) AS by_compiler, change, object_name,
       detail, CASE WHEN status_code = 200 THEN 'done' WHEN status_code IN (401, 403) THEN 'denied' ELSE 'failed' END AS outcome,
       error_message, workspace_id, source_ip_address, request_id
FROM (
  SELECT a.event_time AS changed_at, a.event_date, a.user_identity.email AS changed_by, a.response.status_code,
         a.response.error_message, a.workspace_id, a.source_ip_address, a.request_id,
         coalesce(p.securable_full_name, p.full_name_arg, p.name_arg,
                  nullif(concat_ws('.', p.catalog_name, p.schema_name, p.name), '')) AS object_name,
         CASE WHEN a.action_name = 'updatePermissions' THEN 'privileges'
              WHEN p.owner IS NOT NULL THEN 'owner'
              WHEN a.action_name LIKE 'create%' THEN 'create'
              WHEN a.action_name LIKE 'delete%' THEN 'drop'
              ELSE 'alter or write' END AS change,
         CASE WHEN a.action_name = 'updatePermissions' THEN concat(lower(p.securable_type), ' ', p.changes)
              WHEN p.owner IS NOT NULL THEN concat('new owner ', p.owner)
              WHEN a.action_name LIKE 'create%' THEN concat(a.action_name, coalesce(concat(' ', p.table_type), ''))
              WHEN a.action_name = 'updateTables' THEN 'updateTables (data or definition)'
              ELSE a.action_name END AS detail
  FROM (SELECT *, request_params AS p FROM system.access.audit
        WHERE service_name = 'unityCatalog' AND action_name IN ({actions})
          -- a CREATE TABLE ... AS stages first: only a refused staging is news (a done one is logged as createTable)
          AND NOT (action_name = 'createStagingTable' AND response.status_code = 200)) a)
WHERE (object_name = '{c}' OR startswith(object_name, '{c}.'))
  -- the compiler's own data writes and staging tables are in governance.compile_log; its grants, owners and views stay
  AND NOT (coalesce(changed_by = '{m}', false) AND (change = 'alter or write' OR contains(object_name, '._stage_')))""",
        "entitlement_changes": f"""SELECT user_principal, change_type, valid_from, valid_to, valid_to IS NULL AS is_current,
       personas, lag(personas) OVER w AS personas_before,
       array_sort(map_keys(grants)) AS granted_pairs, lag(array_sort(map_keys(grants))) OVER w AS granted_pairs_before,
       own_win, sees_rows
FROM {G}.user_entitlement_history
WINDOW w AS (PARTITION BY user_principal ORDER BY valid_from)""",
        "compile_runs": f"""SELECT run_at, step, duration_s, run_by, detail, source_versions, run_id FROM {G}.compile_log""",
    }
    assert list(views) == config.AUDIT_VIEWS, "config.AUDIT_VIEWS must list the audit views"
    return views


def generate_audit():
    """The audit schema holds exactly the audit views, each as generated (recreated when its SQL changes or it was
    edited); the auditors may read it. A view that can't be created (for example the compiler can't read a system
    table) is reported and the job fails; the others are in place."""
    t0 = time.time()
    ensure_tables()
    me = q("SELECT session_user()")[0][0]
    q(f"""CREATE SCHEMA IF NOT EXISTS {C}.{AUDIT}
COMMENT 'Generated audit views over the system tables and the governance history. The admin and the auditors only.'""")
    want = audit_views(me)
    have = {v: (d, s) for v, d, s, _ in q(f"SELECT * FROM {G}.audit_views")}
    live = {v: d for v, d in q(f"""SELECT table_name, sha2(view_definition, 256) FROM {C}.information_schema.views
                                     WHERE table_schema = '{AUDIT}'""")}
    made, failed = 0, []
    for v, sql in want.items():
        desired_sha = hashlib.sha256(sql.encode()).hexdigest()
        rec = have.get(v)
        if rec and rec[0] == desired_sha and live.get(v) == rec[1]:
            continue
        try:
            q(f"CREATE OR REPLACE VIEW {C}.{AUDIT}.`{v}` COMMENT '{AUDIT_COMMENT}' AS {sql}")
        except RuntimeError as err:
            failed.append(v)
            msg = " ".join(str(err).split())[:300]  # the server's message can start with a blank line
            print(f"audit: ERROR {AUDIT}.{v} could not be (re)created: {msg}")
            if "system" in msg.lower():
                print("audit: the compiler needs: GRANT USE CATALOG ON CATALOG system; GRANT USE SCHEMA, SELECT ON SCHEMA "
                      "system.access and system.query (poc.py deploy grants them; a metastore admin must)")
            drop(f"DROP VIEW IF EXISTS {C}.{AUDIT}.`{v}`", v, failed, AUDIT, "audit_views")
            continue
        stored = q(f"""SELECT sha2(view_definition, 256) FROM {C}.information_schema.views
                       WHERE table_schema = '{AUDIT}' AND table_name = '{lit(v)}'""")[0][0]
        q(f"DELETE FROM {G}.audit_views WHERE view_name = '{lit(v)}'")
        q(f"INSERT INTO {G}.audit_views VALUES ('{lit(v)}', '{desired_sha}', '{stored}', current_timestamp())")
        print(f"audit: {AUDIT}.{v} ({'new' if not rec else 'changed or edited'})")
        made += 1
    # nothing but the audit views in the audit schema
    for v, kind in q(f"SELECT table_name, table_type FROM {C}.information_schema.tables WHERE table_schema = '{AUDIT}'"):
        if kind == "VIEW" and v in want:
            continue
        what = {"VIEW": "VIEW", "METRIC_VIEW": "VIEW", "MATERIALIZED_VIEW": "MATERIALIZED VIEW", "STREAMING_TABLE": "TABLE"}.get(kind, "TABLE")
        if drop(f"DROP {what} {C}.{AUDIT}.`{v}`", v, failed, AUDIT, "audit_views"):
            print(f"audit: WARNING dropped {AUDIT}.{v} ({kind}): only the audit views may be in {AUDIT}")
    for f, in q(f"SELECT specific_name FROM {C}.information_schema.routines WHERE specific_schema = '{AUDIT}'"):
        if drop(f"DROP FUNCTION {C}.{AUDIT}.`{f}`", f, failed, AUDIT, "audit_views"):
            print(f"audit: WARNING dropped function {AUDIT}.{f}")
    for vol, in q(f"SELECT volume_name FROM {C}.information_schema.volumes WHERE volume_schema = '{AUDIT}'"):
        if drop(f"DROP VOLUME {C}.{AUDIT}.`{vol}`", vol, failed, AUDIT, "audit_views"):
            print(f"audit: WARNING dropped volume {AUDIT}.{vol}")
    q(f"DELETE FROM {G}.audit_views WHERE view_name NOT IN ({', '.join(chr(39) + lit(v) + chr(39) for v in want)})")
    # the auditors read the audit schema (granted only when missing: every grant is itself an audit event)
    held = {(who, priv) for who, priv in q(f"""SELECT grantee, privilege_type FROM {C}.information_schema.schema_privileges
                                              WHERE schema_name = '{AUDIT}' AND inherited_from = 'NONE'""")}
    for who in config.AUDITORS:
        missing = [p for p in ("USE_SCHEMA", "SELECT") if (who, p) not in held]
        if missing:
            try:
                q(f"GRANT {', '.join(p.replace('_', ' ') for p in missing)} ON SCHEMA {C}.{AUDIT} TO `{who}`")
                print(f"audit: {who} may read {AUDIT}")
            except RuntimeError as err:
                failed.append(f"grant to {who}")
                print(f"audit: ERROR could not grant {who} read on {AUDIT}: {' '.join(str(err).split())[:160]}")
    log("audit", t0, f"{len(want)} audit views, {made} (re)created" + (f", FAILED {failed}" if failed else ""), {})
    print(f"audit: {len(want)} audit views, {made} (re)created ({time.time() - t0:.0f}s)")
    if failed:
        raise RuntimeError(f"audit views not (re)created: {failed}")


# ---------------------------------------------------------------------------------------------------- guard
def guard():
    """Nobody but the compiler and the admin may hold a privilege on the restricted schemas, their objects, or the
    catalog (other than USE CATALOG); the configured data loaders also on the schemas they load (hr_base, policy);
    on the views schema, others may only read; on the audit schema, only the auditors may read. The compiler owns the catalog, the schemas and every object (the
    loaders may own what they create in the schemas they load). Revokes or reassigns anything else and reports it.
    Every statement is tried on its own: one that fails is reported and the job fails, after everything else ran."""
    t0 = time.time()
    me = q("SELECT session_user()")[0][0]  # the guard runs as the compiler: the identity that must own everything
    core = {me, config.ADMIN}  # on the catalog, the entitlements and the views schema: nobody else
    loaders = {me, config.ADMIN, *config.ETL_PRINCIPALS}  # on the schemas the data loaders write to
    allowed = {BASE: loaders, config.EXPORTS: loaders, config.GOV: core}
    fixed, failed = [], []

    def act(sql, what):
        try:
            q(sql)
            fixed.append(what)
        except RuntimeError as err:
            failed.append(f"{what}: {' '.join(str(err).split())[:160]}")

    cat_owner = q(f"SELECT catalog_owner FROM {C}.information_schema.catalogs WHERE catalog_name = '{C}'")[0][0]
    if cat_owner != me:  # the compiler cannot take the catalog back itself: the admin must
        failed.append(f"the catalog is owned by {cat_owner}, not the compiler ({me}): ALTER CATALOG {C} OWNER TO `{me}`")
    for sch, own in q(f"""SELECT schema_name, schema_owner FROM {C}.information_schema.schemata
                          WHERE schema_name IN ('{BASE}', '{config.EXPORTS}', '{config.GOV}', '{SECURE}', '{AUDIT}')"""):
        if own != me:
            act(f"ALTER SCHEMA {C}.{sch} OWNER TO `{me}`", f"ownership of schema {sch} (was {own})")
    for s, o, kind, own in q(f"""SELECT table_schema, table_name, table_type, table_owner FROM {C}.information_schema.tables
                                 WHERE table_schema IN ('{BASE}', '{config.EXPORTS}', '{config.GOV}', '{SECURE}', '{AUDIT}')"""):
        if own == me or (own in config.ETL_PRINCIPALS and s in (BASE, config.EXPORTS)):
            continue
        if kind in ("MATERIALIZED_VIEW", "STREAMING_TABLE"):  # owned by their pipeline: report, don't re-own
            failed.append(f"{kind} {s}.{o} is owned by {own}, not the compiler")
            continue
        act(f"ALTER {'VIEW' if kind == 'VIEW' else 'TABLE'} {C}.{s}.`{o}` OWNER TO `{me}`", f"ownership of {s}.{o} (was {own})")
    # information_schema spells privileges with underscores (USE_CATALOG); SQL statements take spaces
    for who, priv in q(f"""SELECT grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.catalog_privileges
                           WHERE catalog_name = '{C}' AND inherited_from = 'NONE'"""):
        if who not in core and priv != "USE CATALOG":
            act(f"REVOKE {priv} ON CATALOG {C} FROM `{who}`", f"{priv} ON CATALOG to {who}")
    for s in (BASE, config.EXPORTS, config.GOV):
        for who, priv in q(f"""SELECT grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.schema_privileges
                               WHERE schema_name = '{s}' AND inherited_from = 'NONE'"""):
            if who not in allowed[s]:
                act(f"REVOKE {priv} ON SCHEMA {C}.{s} FROM `{who}`", f"{priv} ON SCHEMA {s} to {who}")
        for t, who, priv in q(f"""SELECT table_name, grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.table_privileges
                                  WHERE table_schema = '{s}' AND inherited_from = 'NONE'"""):
            if who not in allowed[s]:
                act(f"REVOKE {priv} ON TABLE {C}.{s}.`{t}` FROM `{who}`", f"{priv} ON TABLE {s}.{t} to {who}")
        for kind, view, col in (("VOLUME", "volume_privileges", "volume"), ("FUNCTION", "routine_privileges", "specific")):
            for o, who, priv in q(f"""SELECT {col}_name, grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.{view}
                                      WHERE {col}_schema = '{s}' AND inherited_from = 'NONE'"""):
                if who not in allowed[s]:
                    act(f"REVOKE {priv} ON {kind} {C}.{s}.`{o}` FROM `{who}`", f"{priv} ON {kind} {s}.{o} to {who}")
    for sch in (SECURE, AUDIT):
        for kind, view, col in (("VOLUME", "volume_privileges", "volume"), ("FUNCTION", "routine_privileges", "specific")):
            for o, who, priv in q(f"""SELECT {col}_name, grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.{view}
                                      WHERE {col}_schema = '{sch}' AND inherited_from = 'NONE'"""):
                if who not in core:  # nothing but generated views belongs there (the views and audit steps drop it)
                    act(f"REVOKE {priv} ON {kind} {C}.{sch}.`{o}` FROM `{who}`", f"{priv} ON {kind} {sch}.{o} to {who}")
    # the views schema: users may read it, nothing more (no new tables or views of their own)
    for who, priv in q(f"""SELECT grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.schema_privileges
                           WHERE schema_name = '{SECURE}' AND inherited_from = 'NONE'"""):
        if who not in core and priv not in ("USE SCHEMA", "SELECT"):
            act(f"REVOKE {priv} ON SCHEMA {C}.{SECURE} FROM `{who}`", f"{priv} ON SCHEMA {SECURE} to {who}")
    for t, who, priv in q(f"""SELECT table_name, grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.table_privileges
                              WHERE table_schema = '{SECURE}' AND inherited_from = 'NONE'"""):
        if who not in core:  # users read the views through the schema grant; nothing on a single view
            act(f"REVOKE {priv} ON TABLE {C}.{SECURE}.`{t}` FROM `{who}`", f"{priv} ON VIEW {SECURE}.{t} to {who}")
    # the audit schema: the auditors may read it, nobody else may hold anything (the admin and the compiler aside)
    for who, priv in q(f"""SELECT grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.schema_privileges
                           WHERE schema_name = '{AUDIT}' AND inherited_from = 'NONE'"""):
        if who not in core and not (who in config.AUDITORS and priv in ("USE SCHEMA", "SELECT")):
            act(f"REVOKE {priv} ON SCHEMA {C}.{AUDIT} FROM `{who}`", f"{priv} ON SCHEMA {AUDIT} to {who}")
    for t, who, priv in q(f"""SELECT table_name, grantee, replace(privilege_type, '_', ' ') FROM {C}.information_schema.table_privileges
                              WHERE table_schema = '{AUDIT}' AND inherited_from = 'NONE'"""):
        if who not in core:  # the auditors read through the schema grant
            act(f"REVOKE {priv} ON TABLE {C}.{AUDIT}.`{t}` FROM `{who}`", f"{priv} ON VIEW {AUDIT}.{t} to {who}")
    for msg in fixed:
        print(f"guard: WARNING revoked or reassigned {msg}")
    for msg in failed:
        print(f"guard: ERROR {msg}")
    log("guard", t0, f"{len(fixed)} revoked or reassigned" + (": " + "; ".join(fixed) if fixed else "")
        + (f"; FAILED: {'; '.join(failed)}" if failed else ""), source_versions())
    print(f"guard: {len(fixed)} unexpected privilege(s) or owner(s) fixed")
    if failed:  # fail the job so it alerts; everything that could be fixed was
        raise RuntimeError(f"guard could not fix {len(failed)} item(s): {failed}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("step", nargs="?", default="all", choices=["entitlements", "views", "audit", "guard", "all"])
    ap.add_argument("--as", dest="who", default=None, help="run as this principal (locally: compiler)")
    a = ap.parse_args()
    w = dbsql.client(a.who)
    errors = []
    for name, fn in (("entitlements", compile_entitlements), ("views", generate_views), ("audit", generate_audit),
                     ("guard", guard)):
        if a.step in (name, "all"):
            try:
                fn()
            except RuntimeError as err:  # as in the job (run_if: ALL_DONE): the guard still runs, then the run fails
                if a.step != "all":
                    raise
                errors.append(f"{name}: {err}")
                print(f"{name}: FAILED: {err}")
    if errors:
        raise RuntimeError(f"{len(errors)} step(s) failed: {errors}")
